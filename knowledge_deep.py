def find_deep_topic(text):
    """Tìm kiến thức chuyên sâu từ 2 cẩm nang."""
    text_lower = text.lower()
    best_match = None
    best_score = 0
    
    for topic_id, data in {**DEEP_KNOWLEDGE_NUOC_GIAT, **DEEP_KNOWLEDGE_NUOC_XA}.items():
        score = sum(1 for kw in data["keywords"] if kw in text_lower)
        if score > best_score:
            best_score = score
            best_match = data
    
    if best_match and best_score > 0:
        return f"{best_match['title']}\n\n{best_match['answer']}"
    return None
